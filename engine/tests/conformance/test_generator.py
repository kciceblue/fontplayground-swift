def test_generator_removes_stale_files(generated, tmp_path):
    out, swift = tmp_path / "fixtures", tmp_path / "swift"
    shutil.copytree(generated[0], out)
    old = out / "planner/old.json"
    old.write_text("{}")
    stale_name = out / "naming/old.json"
    stale_name.write_text("{}")
    sentinel = out / "shaping/foreign.json"
    sentinel.parent.mkdir(exist_ok=True)
    sentinel.write_bytes(b"unowned\n")
    (out / "languages/retired.json").write_text("preserved")
    readme = (out / "README.md").read_bytes()
    assert_success(run_generator(out, swift))
    assert not old.exists() and not stale_name.exists()
    assert (out / "naming/family-names.json").read_bytes() == (FIXTURES / "naming/family-names.json").read_bytes()
    assert sentinel.read_bytes() == b"unowned\n"
    assert (out / "languages/retired.json").read_text() == "preserved"
    assert (out / "README.md").read_bytes() == readme


