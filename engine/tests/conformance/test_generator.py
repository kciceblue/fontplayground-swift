def test_frozen_fixtures_are_verified_not_regenerated(generated):
    out = generated[0]
    assert all((out / name).read_bytes() == (FIXTURES / name).read_bytes() for name in FROZEN_FILES)
    manifest = (FIXTURES / "FROZEN.sha256").read_text(encoding="utf-8")
    assert manifest == "".join(
        f"{hashlib.sha256((FIXTURES / name).read_bytes()).hexdigest()}  {name}\n" for name in sorted(FROZEN_FILES)
    )
    result = run_generator(out, generated[1])
    assert_success(result)
    assert result.stdout.count(f"frozen: {len(FROZEN_FILES)} files verified") == 1
    assert "frozen (reference/ removed)" not in result.stdout


def test_frozen_fixture_change_is_rejected(generated, tmp_path):
    out, swift = tmp_path / "fixtures", tmp_path / "swift"
    shutil.copytree(generated[0], out)
    path = out / "languages/languages.json"
    data = bytearray(path.read_bytes())
    data[-2] ^= 1
    path.write_bytes(bytes(data))
    planner = (out / "planner/cases.json").read_bytes()
    (out / "planner/cases.json").write_text("stale")
    result = run_generator(out, swift)
    assert result.returncode == 1
    assert FROZEN_MESSAGE.format("languages/languages.json") in result.stderr
    # Verification runs before any write.
    assert (out / "planner/cases.json").read_text() == "stale" and not swift.exists()
    path.unlink()
    result = run_generator(out, swift)
    assert result.returncode == 1 and FROZEN_MESSAGE.format("languages/languages.json") in result.stderr
    shutil.copyfile(generated[0] / "languages/languages.json", path)
    (out / "planner/cases.json").write_bytes(planner)
    assert_success(run_generator(out, swift))


def test_frozen_manifest_must_list_every_frozen_fixture(generated, tmp_path):
    out, swift = tmp_path / "fixtures", tmp_path / "swift"
    shutil.copytree(generated[0], out)
    manifest = out / "FROZEN.sha256"
    lines = manifest.read_text(encoding="utf-8").splitlines(keepends=True)
    manifest.write_text("".join(line for line in lines if not line.endswith("  text/ignorable.json\n")))
    result = run_generator(out, swift)
    assert result.returncode == 1 and FROZEN_MESSAGE.format("text/ignorable.json") in result.stderr
    manifest.unlink()
    result = run_generator(out, swift)
    assert result.returncode == 1 and FROZEN_MESSAGE.format("FROZEN.sha256") in result.stderr


def test_writer_is_compact_atomic_and_rejects_nan(tmp_path):
    sys.path.insert(0, str(TOOLS))
    from common import dump

    path = tmp_path / "test.json"
    dump(path, {"scalar_array": [1, "é", None], "nested": [[32, 126]], "fraction": 0.1})
    before = path.read_bytes()
    assert b'"scalar_array": [1, "\xc3\xa9", null]' in before
    assert b'"nested": [\n    [32, 126]\n  ]' in before
    with pytest.raises(ValueError):
        dump(path, {"invalid": float("nan")})
    assert path.read_bytes() == before and set(tmp_path.iterdir()) == {path}
