def run_generator(out, swift, *arguments, seed="0"):
    return subprocess.run(
        [
            sys.executable,
            str(TOOLS / "generate.py"),
            "--out",
            str(out),
            "--swift-out",
            str(swift),
            *map(str, arguments),
        ],
        capture_output=True,
        text=True,
        env={**os.environ, "PYTHONHASHSEED": seed},
        timeout=30,
    )


def assert_success(result):
    assert result.returncode == 0, result.stdout + result.stderr


def tree(path):
    return {file.relative_to(path).as_posix(): file.read_bytes() for file in path.rglob("*") if file.is_file()}


def read(out, relative):
    return json.loads((out / relative).read_text(encoding="utf-8"))


def seed_frozen(out):
    """The generator cannot recreate frozen fixtures, so an output tree starts from the committed ones."""
    for relative in (*FROZEN_FILES, "FROZEN.sha256"):
        (out / relative).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(FIXTURES / relative, out / relative)
    return out


@pytest.fixture(scope="module")
def generated(tmp_path_factory):
    directory = tmp_path_factory.mktemp("conformance")
    out, swift = seed_frozen(directory / "fixtures"), directory / "swift"
    assert_success(run_generator(out, swift))
    return out, swift


def test_fixture_files_and_headers(generated):
    out, swift = generated
    expected = JSON_FILES | {"README.md", "FROZEN.sha256"}
    if importlib.util.find_spec("fpengine.shaping") is not None:
        expected.add("shaping/ot_alternatives.json")
    assert set(tree(out)) == expected
    assert set(tree(swift)) == {"ScriptGroupTable.swift"}
    for relative in JSON_FILES:
        value = read(out, relative)
        assert next(iter(value)) == "header"
        header = value["header"]
        assert set(header) == HEADER_KEYS
        assert header["generator_version"] == 1
        assert header["category"] == relative.removesuffix(".json")
        assert header["python"] == f"{sys.version_info.major}.{sys.version_info.minor}"
        assert header["seed"] in (None, 20260929)
        assert (header["reference"] is None) == (relative not in FROZEN_FILES)
        assert header["sources"] and header["note"] == "Generated by `make conformance`. Never edit by hand."
        raw = (out / relative).read_bytes()
        assert raw.endswith(b"\n") and b"\r" not in raw
        assert str(ROOT).encode() not in raw


def test_generator_is_deterministic(generated, tmp_path):
    out, swift = generated
    other_out, other_swift = seed_frozen(tmp_path / "fixtures"), tmp_path / "swift"
    assert_success(run_generator(other_out, other_swift, seed="1"))
    assert tree(out) == tree(other_out)
    assert tree(swift) == tree(other_swift)
    original = {p: p.stat().st_mtime_ns for root in (other_out, other_swift) for p in root.rglob("*") if p.is_file()}
    result = run_generator(other_out, other_swift)
    assert_success(result)
    # WP-107 owns shaping serialization and may replace its file even for identical bytes.
    assert all(p.stat().st_mtime_ns == stamp for p, stamp in original.items() if p.parent.name != "shaping")
    assert "unchanged" in result.stdout


