def test_swift_table_matches_json(generated):
    data = read(generated[0], "scripts/group-ranges.json")
    swift = (generated[1] / "ScriptGroupTable.swift").read_text()
    assert swift.startswith("// swift-format-ignore-file\n")
    for name, expected in (
        ("starts", [row[0] for row in data["ranges"]]),
        ("groups", [data["groups"].index(row[2]) for row in data["ranges"]]),
    ):
        body = re.search(rf"static let {name}: \[UInt\d+\] = \[(.*?)\]", swift, re.S).group(1)
        lines = [line.strip().removesuffix(",").split(", ") for line in body.splitlines() if line.strip()]
        assert all(len(line) == 8 for line in lines[:-1])
        assert [int(value, 0) for line in lines for value in line] == expected


